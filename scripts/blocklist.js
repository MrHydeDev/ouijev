/** The fingerprint of a word as the blocklist keeps it. */
const fingerprint = (word) => createHash("sha256").update(word).digest("hex").slice(0, 16);

/**
 * A test for the blocked words of `lang`.
 *
 * @param {"es" | "en"} lang
 * @returns {(word: string) => boolean}
 */
export function isBlocked(lang) {
  const blocked = new Set(BLOCKED[lang]);
  return (word) => blocked.has(fingerprint(word));
}
